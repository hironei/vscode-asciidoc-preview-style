'use strict'
/*
 * Pure (vscode-free) logic for the AsciiDoc Preview Light 2026 Style extension.
 * Kept separate from extension.js so it can be unit-tested with `node --test`.
 */

// Name of the generated stylesheet. removeStyleSetting() uses it (together with
// EXTENSION_ID) to recognize a setting value this extension wrote.
const BUNDLE_NAME = 'asciidoc-preview-light-2026.css'
const EXTENSION_ID = 'hironei.vscode-asciidoc-preview-style'

// First Asciidoctor VS Code version whose `asciidoc.previewStyles` contribution
// is loadable by the preview webview. null = no fixed version is known yet, so
// the workaround always applies in `auto` mode. Set it once upstream is fixed.
const UPSTREAM_FIXED_VERSION = null

// Mirrors DEFAULT_STYLE_SHEETS of Asciidoctor VS Code 4.3.0. These are the
// standard stylesheets that `asciidoc.preview.style` would otherwise replace.
const DEFAULT_STYLE_SHEETS = {
  vscode: ['asciidoctor-editor.css', 'asciidoctor-editor-enhancements.css'],
  asciidoctor: ['asciidoctor-default.css'],
  antora: ['asciidoctor-default.css', 'asciidoctor-antora.css'],
  github: [
    'asciidoctor-default.css',
    'asciidoctor-github-colors.css',
    'asciidoctor-github.css',
  ],
}

/** Effective default style (empty = automatic -> vscode, unless legacy useEditorStyle is false). */
function resolveDefaultStyle(defaultStyle, useEditorStyle) {
  if (typeof defaultStyle === 'string' && DEFAULT_STYLE_SHEETS[defaultStyle]) {
    return defaultStyle
  }
  return useEditorStyle === false ? 'asciidoctor' : 'vscode'
}

/** Concatenate the standard stylesheets and Light 2026 (ours last). */
function buildBundle(style, readStandard, ownCss) {
  const parts = [
    `/* Generated by ${EXTENSION_ID}. Do not edit: overwritten on activation. */`,
  ]
  for (const file of DEFAULT_STYLE_SHEETS[style]) {
    parts.push(`/* ---- standard: ${file} ---- */`, readStandard(file))
  }
  parts.push('/* ---- Light 2026 ---- */', ownCss)
  return parts.join('\n') + '\n'
}

function parseVersion(v) {
  const m = /^(\d+)\.(\d+)\.(\d+)/.exec(String(v || ''))
  return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : undefined
}

/** True when the installed Asciidoctor VS Code is at/after the known fixed version. */
function isUpstreamFixed(installedVersion, fixedVersion = UPSTREAM_FIXED_VERSION) {
  if (!fixedVersion) return false
  const a = parseVersion(installedVersion)
  const b = parseVersion(fixedVersion)
  if (!a || !b) return false
  for (let i = 0; i < 3; i++) {
    if (a[i] !== b[i]) return a[i] > b[i]
  }
  return true
}

/**
 * Decide what to do with the user-scope `asciidoc.preview.style` value.
 * Never overwrites a value the user set; never re-applies after the user cleared it.
 *
 * @returns {{action:'set'|'refresh'|'remove'|'none', owned:string|undefined, optedOut:boolean, reason:string}}
 */
function decide({ mode, upstreamFixed, current, target, owned, optedOut, forceEnable }) {
  const cur = current || ''
  const mine = cur !== '' && (cur === target || cur === owned)

  if (mode === 'off' || upstreamFixed) {
    const reason = upstreamFixed ? 'upstream-fixed' : 'mode-off'
    return mine
      ? { action: 'remove', owned: undefined, optedOut: false, reason }
      : { action: 'none', owned: undefined, optedOut: false, reason }
  }
  if (mine) {
    return cur === target
      ? { action: 'refresh', owned: target, optedOut: false, reason: 'owned' }
      : { action: 'set', owned: target, optedOut: false, reason: 'migrate' }
  }
  if (cur === '') {
    if (forceEnable) return { action: 'set', owned: target, optedOut: false, reason: 'enable' }
    if (optedOut || owned !== undefined) {
      return { action: 'none', owned, optedOut: true, reason: 'user-cleared' }
    }
    return { action: 'set', owned: target, optedOut: false, reason: 'initial' }
  }
  return { action: 'none', owned: undefined, optedOut, reason: 'user-value' }
}

function skipString(text, i) {
  // text[i] === '"'; returns index of the closing quote
  let j = i + 1
  while (j < text.length && text[j] !== '"') j += text[j] === '\\' ? 2 : 1
  return j
}

function skipTrivia(text, i) {
  for (;;) {
    while (i < text.length && /\s/.test(text[i])) i++
    if (text[i] === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i++
    } else if (text[i] === '/' && text[i + 1] === '*') {
      const e = text.indexOf('*/', i + 2)
      i = e < 0 ? text.length : e + 2
    } else {
      return i
    }
  }
}

/** Locate a top-level string-valued property of a JSONC object. */
function findTopLevelStringProperty(text, key) {
  let depth = 0
  let expectKey = false
  let i = 0
  while (i < text.length) {
    const c = text[i]
    if (c === '/' && (text[i + 1] === '/' || text[i + 1] === '*')) {
      i = skipTrivia(text, i)
      continue
    }
    if (c === '"') {
      const j = skipString(text, i)
      if (depth === 1 && expectKey) {
        let k
        try { k = JSON.parse(text.slice(i, j + 1)) } catch { k = undefined }
        if (k === key) {
          let v = skipTrivia(text, j + 1)
          if (text[v] !== ':') return undefined
          v = skipTrivia(text, v + 1)
          if (text[v] !== '"') return undefined
          const ve = skipString(text, v)
          let value
          try { value = JSON.parse(text.slice(v, ve + 1)) } catch { return undefined }
          return { start: i, end: ve + 1, value }
        }
      }
      i = j + 1
      continue
    }
    if (c === '{' || c === '[') { depth++; if (depth === 1 && c === '{') expectKey = true }
    else if (c === '}' || c === ']') depth--
    else if (c === ',' && depth === 1) expectKey = true
    else if (c === ':' && depth === 1) expectKey = false
    i++
  }
  return undefined
}

function samePath(a, b) {
  const n = (p) => String(p).replace(/\\/g, '/').replace(/\/+$/, '')
  return process.platform === 'win32' || /^[a-z]:/i.test(a) ? n(a).toLowerCase() === n(b).toLowerCase() : n(a) === n(b)
}

/**
 * Remove the top-level `"asciidoc.preview.style"` entry from settings.json text
 * (JSONC) only when its value equals expectedValue (the bundle this extension
 * wrote). Nested keys, other values and everything else are kept.
 * Returns the new text, or the original string if nothing matched.
 */
function removeStyleSetting(text, expectedValue) {
  if (!expectedValue) return text
  const prop = findTopLevelStringProperty(text, 'asciidoc.preview.style')
  if (!prop || !samePath(prop.value, expectedValue)) return text
  let start = prop.start
  let end = prop.end
  // extend over indentation back to the line start (when only blanks precede)
  let ls = start
  while (ls > 0 && (text[ls - 1] === ' ' || text[ls - 1] === '\t')) ls--
  if (ls === 0 || text[ls - 1] === '\n') start = ls
  const after = skipTrivia(text, end)
  if (text[after] === ',') {
    end = after + 1
  } else if (text[after] === '}') {
    // last entry: drop the previous entry's trailing comma
    let k = start
    while (k > 0 && /\s/.test(text[k - 1])) k--
    if (text[k - 1] === ',') {
      return text.slice(0, k - 1) + text.slice(k, start) + text.slice(removeTail(text, end))
    }
  }
  return text.slice(0, start) + text.slice(removeTail(text, end))
}

function removeTail(text, end) {
  let e = end
  while (text[e] === ' ' || text[e] === '\t') e++
  if (text[e] === '\r') e++
  if (text[e] === '\n') e++
  else e = end
  return e
}

module.exports = {
  BUNDLE_NAME,
  EXTENSION_ID,
  UPSTREAM_FIXED_VERSION,
  DEFAULT_STYLE_SHEETS,
  resolveDefaultStyle,
  buildBundle,
  isUpstreamFixed,
  decide,
  removeStyleSetting,
}
